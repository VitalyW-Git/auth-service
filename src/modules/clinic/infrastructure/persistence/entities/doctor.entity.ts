import {
	Check,
	Entity,
	Index,
	ManyToOne,
	PrimaryKey,
	Property
} from '@mikro-orm/core'
import { v4 } from 'uuid'

import { ClinicEntity } from '@/modules/clinic/infrastructure/persistence/entities/clinic.entity'
import { UserEntity } from '@/modules/user/infrastructure/persistence/entities/user.entity'

@Entity({ tableName: 'doctors' })
@Index({ properties: ['clinic', 'sortOrder'] })
export class DoctorEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Doctor identifier, generated by the application'
	})
	id: string = v4()

	@Property({
		fieldName: 'full_name',
		type: 'text',
		comment: 'Doctor name shown to staff and patients'
	})
	fullName!: string

	@Property({
		type: 'text',
		comment: 'Specialty shown under the name, e.g. Therapist'
	})
	specialty!: string

	@Property({
		fieldName: 'sort_order',
		default: 0,
		comment: 'Position of the doctor column in the schedule, ascending'
	})
	sortOrder: number = 0

	@Property({
		fieldName: 'archived_at',
		nullable: true,
		comment: 'Time the doctor stopped working; NULL for active doctors'
	})
	archivedAt?: Date

	@ManyToOne(() => ClinicEntity, {
		fieldName: 'clinic_id',
		deleteRule: 'cascade',
		comment: 'Clinic the doctor works in, references clinics'
	})
	clinic!: ClinicEntity

	@Index()
	@ManyToOne(() => UserEntity, {
		fieldName: 'user_id',
		nullable: true,
		deleteRule: 'set null',
		comment:
			'Login of the doctor, references users; NULL if the doctor has no login'
	})
	user?: UserEntity

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Creation time, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
