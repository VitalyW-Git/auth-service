import {
	Entity,
	Enum,
	Index,
	ManyToOne,
	PrimaryKey,
	Property,
	Unique
} from '@mikro-orm/core'
import { v4 } from 'uuid'

import { ClinicMemberRole } from '@/modules/clinic/domain/common/enums/clinic-member-role.enum'
import { ClinicEntity } from '@/modules/clinic/infrastructure/persistence/entities/clinic.entity'
import { UserEntity } from '@/modules/user/infrastructure/persistence/entities/user.entity'

@Entity({ tableName: 'clinic_members' })
@Unique({ properties: ['clinic', 'user'] })
export class ClinicMemberEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Membership identifier, generated by the application'
	})
	id: string = v4()

	@Enum({
		items: () => ClinicMemberRole,
		comment: 'Access level of the user in the clinic'
	})
	role!: ClinicMemberRole

	@ManyToOne(() => ClinicEntity, {
		fieldName: 'clinic_id',
		deleteRule: 'cascade',
		comment: 'Clinic the user has access to, references clinics'
	})
	clinic!: ClinicEntity

	@Index()
	@ManyToOne(() => UserEntity, {
		fieldName: 'user_id',
		deleteRule: 'cascade',
		comment: 'Staff account, references users'
	})
	user!: UserEntity

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Time access was granted, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
