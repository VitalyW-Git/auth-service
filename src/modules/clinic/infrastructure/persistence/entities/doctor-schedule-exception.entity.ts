import {
	Check,
	Entity,
	Enum,
	Index,
	ManyToOne,
	PrimaryKey,
	Property
} from '@mikro-orm/core'
import { v4 } from 'uuid'

import { ScheduleExceptionKind } from '@/modules/clinic/domain/common/enums/schedule-exception-kind.enum'
import { DoctorEntity } from '@/modules/clinic/infrastructure/persistence/entities/doctor.entity'

@Entity({ tableName: 'doctor_schedule_exceptions' })
@Index({ properties: ['doctor', 'startsOn'] })
@Check({
	name: 'doctor_schedule_exceptions_date_range_check',
	expression: `"ends_on" >= "starts_on"`
})
@Check({
	name: 'doctor_schedule_exceptions_hours_check',
	expression: `("kind" = 'DAY_OFF' and "start_time" is null and "end_time" is null) or ("kind" = 'CUSTOM_HOURS' and "start_time" is not null and "end_time" > "start_time")`
})
export class DoctorScheduleExceptionEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Exception identifier, generated by the application'
	})
	id: string = v4()

	@Property({
		fieldName: 'starts_on',
		type: 'date',
		comment: 'First day of the exception, clinic local date'
	})
	startsOn!: string

	@Property({
		fieldName: 'ends_on',
		type: 'date',
		comment: 'Last day of the exception, inclusive'
	})
	endsOn!: string

	@Enum({
		items: () => ScheduleExceptionKind,
		comment: 'Exception type: day off or custom working hours'
	})
	kind!: ScheduleExceptionKind

	@Property({
		fieldName: 'start_time',
		type: 'time',
		nullable: true,
		comment:
			'Working hours start on these days, clinic local time; NULL for DAY_OFF'
	})
	startTime?: string

	@Property({
		fieldName: 'end_time',
		type: 'time',
		nullable: true,
		comment:
			'Working hours end on these days, clinic local time; NULL for DAY_OFF'
	})
	endTime?: string

	@Property({
		type: 'text',
		nullable: true,
		comment: 'Reason shown to staff, e.g. vacation; NULL if not given'
	})
	note?: string

	@ManyToOne(() => DoctorEntity, {
		fieldName: 'doctor_id',
		deleteRule: 'cascade',
		comment: 'Doctor the exception applies to, references doctors'
	})
	doctor!: DoctorEntity

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Creation time, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
