import {
	Check,
	Entity,
	ManyToOne,
	PrimaryKey,
	Property,
	Unique
} from '@mikro-orm/core'
import { v4 } from 'uuid'

import { DoctorEntity } from '@/modules/clinic/infrastructure/persistence/entities/doctor.entity'

@Entity({ tableName: 'doctor_working_hours' })
@Unique({ properties: ['doctor', 'weekday', 'startTime'] })
@Check({
	name: 'doctor_working_hours_weekday_check',
	expression: `"weekday" >= 1 and "weekday" <= 7`
})
@Check({
	name: 'doctor_working_hours_time_range_check',
	expression: `"end_time" > "start_time"`
})
export class DoctorWorkingHoursEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Interval identifier, generated by the application'
	})
	id: string = v4()

	@Property({
		type: 'smallint',
		comment: 'ISO day of week: 1 is Monday, 7 is Sunday'
	})
	weekday!: number

	@Property({
		fieldName: 'start_time',
		type: 'time',
		comment: 'Interval start, clinic local time'
	})
	startTime!: string

	@Property({
		fieldName: 'end_time',
		type: 'time',
		comment: 'Interval end, clinic local time'
	})
	endTime!: string

	@ManyToOne(() => DoctorEntity, {
		fieldName: 'doctor_id',
		deleteRule: 'cascade',
		comment: 'Doctor the interval belongs to, references doctors'
	})
	doctor!: DoctorEntity

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Creation time, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
