import { Check, Entity, PrimaryKey, Property } from '@mikro-orm/core'
import { v4 } from 'uuid'

@Entity({ tableName: 'clinics' })
export class ClinicEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Clinic identifier, generated by the application'
	})
	id: string = v4()

	@Property({
		type: 'text',
		comment: 'Display name shown to staff and patients'
	})
	name!: string

	@Property({
		type: 'text',
		comment: 'IANA time zone of the clinic, e.g. Europe/Moscow'
	})
	timezone!: string

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Creation time, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
