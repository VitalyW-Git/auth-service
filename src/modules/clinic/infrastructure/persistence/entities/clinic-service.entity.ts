import {
	Check,
	Entity,
	Index,
	ManyToOne,
	PrimaryKey,
	Property
} from '@mikro-orm/core'
import { v4 } from 'uuid'

import { ClinicEntity } from '@/modules/clinic/infrastructure/persistence/entities/clinic.entity'

@Entity({ tableName: 'clinic_services' })
@Check({
	name: 'clinic_services_duration_minutes_check',
	expression: `"duration_minutes" > 0`
})
export class ClinicServiceEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Service identifier, generated by the application'
	})
	id: string = v4()

	@Property({
		type: 'text',
		comment: 'Service name shown in the schedule and to patients'
	})
	name!: string

	@Property({
		fieldName: 'duration_minutes',
		comment: 'Default appointment length for the service, minutes'
	})
	durationMinutes!: number

	@Property({
		fieldName: 'archived_at',
		nullable: true,
		comment: 'Time the service was withdrawn; NULL for offered services'
	})
	archivedAt?: Date

	@Index()
	@ManyToOne(() => ClinicEntity, {
		fieldName: 'clinic_id',
		deleteRule: 'cascade',
		comment: 'Clinic offering the service, references clinics'
	})
	clinic!: ClinicEntity

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Creation time, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
