import {
	Check,
	Entity,
	Enum,
	Index,
	ManyToOne,
	PrimaryKey,
	Property
} from '@mikro-orm/core'
import { v4 } from 'uuid'

import { AppointmentSource } from '@/modules/appointment/domain/common/enums/appointment-source.enum'
import { AppointmentStatus } from '@/modules/appointment/domain/common/enums/appointment-status.enum'
import { CancellationParty } from '@/modules/appointment/domain/common/enums/cancellation-party.enum'
import { PatientEntity } from '@/modules/appointment/infrastructure/persistence/entities/patient.entity'
import { ClinicServiceEntity } from '@/modules/clinic/infrastructure/persistence/entities/clinic-service.entity'
import { ClinicEntity } from '@/modules/clinic/infrastructure/persistence/entities/clinic.entity'
import { DoctorEntity } from '@/modules/clinic/infrastructure/persistence/entities/doctor.entity'

@Entity({ tableName: 'appointments' })
// Пересечение записей одного врача запрещено exclusion-ограничением (создано миграцией ScheduleSchema,
// нужно расширение btree_gist). MikroORM видит его индекс в базе и сравнивает индексы с expression только
// по имени, поэтому объявление с тем же именем не даёт migration:check счесть индекс лишним.
@Index({
	name: 'appointments_doctor_id_no_overlap',
	expression: `alter table "appointments" add constraint "appointments_doctor_id_no_overlap" exclude using gist ("doctor_id" with =, tstzrange("starts_at", "ends_at") with &&) where ("status" <> 'CANCELLED')`
})
@Index({ properties: ['clinic', 'startsAt'] })
@Index({ properties: ['doctor', 'startsAt'] })
@Index({ properties: ['patient', 'startsAt'] })
@Check({
	name: 'appointments_time_range_check',
	expression: `"ends_at" > "starts_at"`
})
@Check({
	name: 'appointments_cancellation_check',
	expression: `("status" = 'CANCELLED' and "cancelled_at" is not null and "cancelled_by" is not null) or ("status" <> 'CANCELLED' and "cancelled_at" is null and "cancelled_by" is null)`
})
export class AppointmentEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Appointment identifier, generated by the application'
	})
	id: string = v4()

	@Property({
		fieldName: 'starts_at',
		comment: 'Appointment start, UTC'
	})
	startsAt!: Date

	@Property({
		fieldName: 'ends_at',
		comment: 'Appointment end, UTC'
	})
	endsAt!: Date

	@Enum({
		items: () => AppointmentStatus,
		default: AppointmentStatus.PENDING,
		comment:
			'Booking state: pending confirmation, confirmed, completed or cancelled'
	})
	status: AppointmentStatus = AppointmentStatus.PENDING

	@Enum({
		items: () => AppointmentSource,
		comment: 'Booking channel: widget, booking page, phone call or staff'
	})
	source!: AppointmentSource

	@Property({
		fieldName: 'patient_comment',
		type: 'text',
		nullable: true,
		comment: 'Note for the doctor left by the patient; NULL if none'
	})
	patientComment?: string

	@Property({
		fieldName: 'cancelled_at',
		nullable: true,
		comment: 'Cancellation time, UTC; set only for CANCELLED'
	})
	cancelledAt?: Date

	@Enum({
		fieldName: 'cancelled_by',
		items: () => CancellationParty,
		nullable: true,
		comment: 'Who cancelled: PATIENT or CLINIC; set only for CANCELLED'
	})
	cancelledBy?: CancellationParty

	@Property({
		version: true,
		comment: 'Optimistic lock counter, incremented on every update'
	})
	version!: number

	@ManyToOne(() => ClinicEntity, {
		fieldName: 'clinic_id',
		deleteRule: 'cascade',
		comment: 'Clinic of the appointment, references clinics'
	})
	clinic!: ClinicEntity

	@ManyToOne(() => DoctorEntity, {
		fieldName: 'doctor_id',
		deleteRule: 'no action',
		comment: 'Doctor receiving the patient, references doctors'
	})
	doctor!: DoctorEntity

	@ManyToOne(() => PatientEntity, {
		fieldName: 'patient_id',
		deleteRule: 'no action',
		comment: 'Patient card in the same clinic, references patients'
	})
	patient!: PatientEntity

	@Index()
	@ManyToOne(() => ClinicServiceEntity, {
		fieldName: 'service_id',
		deleteRule: 'no action',
		comment: 'Booked service, references clinic_services'
	})
	service!: ClinicServiceEntity

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Time the booking was made, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
