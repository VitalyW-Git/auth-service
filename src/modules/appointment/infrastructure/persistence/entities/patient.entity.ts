import {
	Check,
	Entity,
	Index,
	ManyToOne,
	PrimaryKey,
	Property,
	Unique
} from '@mikro-orm/core'
import { v4 } from 'uuid'

import { ClinicEntity } from '@/modules/clinic/infrastructure/persistence/entities/clinic.entity'
import { UserEntity } from '@/modules/user/infrastructure/persistence/entities/user.entity'

@Entity({ tableName: 'patients' })
@Unique({ properties: ['clinic', 'phone'] })
@Unique({ properties: ['clinic', 'user'] })
export class PatientEntity {
	@PrimaryKey({
		type: 'uuid',
		comment: 'Patient card identifier, generated by the application'
	})
	id: string = v4()

	@Property({
		fieldName: 'full_name',
		type: 'text',
		comment: 'Name as the patient gave it to this clinic'
	})
	fullName!: string

	@Index()
	@Property({
		length: 16,
		comment: 'Phone in E.164 format, e.g. +79161234567'
	})
	phone!: string

	@ManyToOne(() => ClinicEntity, {
		fieldName: 'clinic_id',
		deleteRule: 'cascade',
		comment: 'Clinic owning the card, references clinics'
	})
	clinic!: ClinicEntity

	@Index()
	@ManyToOne(() => UserEntity, {
		fieldName: 'user_id',
		nullable: true,
		deleteRule: 'set null',
		comment:
			'Patient account, references users; NULL if the card was created by staff without an account'
	})
	user?: UserEntity

	@Property({
		fieldName: 'created_at',
		defaultRaw: 'now()',
		comment: 'Creation time, UTC'
	})
	createdAt: Date = new Date()

	@Property({
		fieldName: 'updated_at',
		defaultRaw: 'now()',
		onUpdate: () => new Date(),
		comment: 'Last modification time, UTC'
	})
	updatedAt: Date = new Date()
}
